from fastapi import APIRouter, HTTPException, Response, Query
from app.storage.repository import ScanRepository
from app.services.report_service import generate_pdf_report

router = APIRouter(prefix="/api", tags=["reports"])

@router.get("/scan/{scan_id}/report")
async def download_report(scan_id: str, format: str = Query("pdf", description="Format: pdf or txt")):
    """
    Downloads full security assessment report in PDF or plain text format.
    """
    report = await ScanRepository.get_scan(scan_id)
    if not report:
        raise HTTPException(status_code=404, detail=f"Scan report '{scan_id}' not found.")

    if format.lower() == "pdf":
        try:
            pdf_bytes = generate_pdf_report(report)
            return Response(
                content=pdf_bytes,
                media_type="application/pdf",
                headers={
                    "Content-Disposition": f'attachment; filename="hackfix-security-report-{scan_id}.pdf"'
                }
            )
        except Exception as e:
            # Fallback to text format if PDF generation encounters an issue
            format = "txt"

    # Plain text format
    findings_text = "\n\n".join([
        f"[{idx+1}] {f.title} ({f.severity.value.upper()})\n"
        f"OWASP: {f.owasp_category}\n"
        f"Endpoint: {f.endpoint}\n"
        f"Explanation: {f.explanation}\n"
        f"Proof: {f.proof}\n"
        f"Advisory Fix: {f.recommendedFix.explanation}\n"
        f"Code:\n{f.recommendedFix.afterCode}"
        for idx, f in enumerate(report.findings)
    ])

    report_text = f"""=====================================================
HACKFIX AI — SECURITY ASSESSMENT REPORT
=====================================================
Target URL:   {report.targetUrl}
Scan ID:      {report.id}
Generated:    {report.createdAt}
Risk Score:   {report.riskScore} / 100
Verdict:      {report.verdict}
Total Issues: {len(report.findings)}

-----------------------------------------------------
DETAILED FINDINGS
-----------------------------------------------------
{findings_text if findings_text else "No vulnerabilities detected during assessment."}

=====================================================
Assessment conducted using external non-destructive URL checks.
Generated by HackFix AI.
"""

    return Response(
        content=report_text,
        media_type="text/plain; charset=utf-8",
        headers={
            "Content-Disposition": f'attachment; filename="hackfix-security-report-{scan_id}.txt"'
        }
    )

